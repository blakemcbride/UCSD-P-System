#!/usr/bin/env python3
#
# UCSD p-System virtual machine
#
# Generate console_font.h: the SDL console's glyphs, pre-rendered from
# DejaVu Sans Mono so the window looks like a terminal without needing a
# font library at run time.  Two sizes are made, for normal and high
# density (HiDPI) displays.  Each glyph is an anti-aliased coverage map,
# one byte (0..255) per pixel.
#
# Only needed when changing the font:
#     python3 console_font.py /path/to/DejaVuSansMono.ttf > console_font.h
#
# Requires Pillow (python3-pillow).

import sys
from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 0x20, 0x7E
SIZES = [("1x", 15), ("2x", 30)]    # pixel sizes: 9x18 and 18x36 cells


def render(path, px):
    font = ImageFont.truetype(path, px)
    ascent, descent = font.getmetrics()
    cw = round(font.getlength("M"))
    ch = ascent + descent
    glyphs = []
    for code in range(FIRST, LAST + 1):
        img = Image.new("L", (cw, ch), 0)
        ImageDraw.Draw(img).text((0, 0), chr(code), font=font, fill=255)
        glyphs.append(img.tobytes())
    return cw, ch, glyphs


def main():
    path = sys.argv[1]
    out = sys.stdout
    out.write("/*\n"
              " * Generated by console_font.py from DejaVu Sans Mono.\n"
              " * DejaVu fonts: Bitstream Vera license, DejaVu changes in\n"
              " * the public domain; see https://dejavu-fonts.github.io/\n"
              " */\n\n"
              "#ifndef UCSDPSYS_VM_CONSOLE_FONT_H\n"
              "#define UCSDPSYS_VM_CONSOLE_FONT_H\n\n"
              "#define CONSOLE_FONT_FIRST 0x%02X\n"
              "#define CONSOLE_FONT_LAST  0x%02X\n\n" % (FIRST, LAST))
    for name, px in SIZES:
        cw, ch, glyphs = render(path, px)
        out.write("#define CONSOLE_FONT_%s_W %d\n" % (name.upper(), cw))
        out.write("#define CONSOLE_FONT_%s_H %d\n" % (name.upper(), ch))
        out.write("static const unsigned char console_font_%s[%d][%d] =\n{\n"
                  % (name, LAST - FIRST + 1, cw * ch))
        for code, data in zip(range(FIRST, LAST + 1), glyphs):
            out.write("    /* %r */ {\n" % chr(code))
            for i in range(0, len(data), 18):
                out.write("        " +
                          ",".join("%d" % b for b in data[i:i + 18]) + ",\n")
            out.write("    },\n")
        out.write("};\n\n")
    out.write("#endif /* UCSDPSYS_VM_CONSOLE_FONT_H */\n")


if __name__ == "__main__":
    main()
